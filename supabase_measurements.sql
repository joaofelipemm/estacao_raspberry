create table if not exists public.measurements (
    id bigint generated by default as identity primary key,
    sync_id uuid not null unique,
    device_id text not null,
    measured_at timestamptz not null,
    temperature double precision not null,
    humidity double precision not null,
    rain_accumulated double precision not null,
    solar_radiation double precision,
    source text not null default 'stm32',
    status text not null default 'synced',
    metadata jsonb not null default '{}'::jsonb
);

alter table public.measurements
add column if not exists solar_radiation double precision;

alter table public.measurements enable row level security;

grant select on table public.measurements to anon, authenticated;
grant insert on table public.measurements to service_role;

drop policy if exists "Measurements are readable by dashboard" on public.measurements;
create policy "Measurements are readable by dashboard"
on public.measurements
for select
to anon, authenticated
using (true);
